// Writes the host configuration files into the built static export, derived
// from policy.mjs so they always match it. `pnpm build` runs it after
// `next build`; the files are never kept in public/.
//
// Files:
//   out/.htaccess              Apache and LiteSpeed: no directory listings,
//                              index.html, the 404 page, UTF-8, the security
//                              headers, Cache-Control, content types, and gzip.
//   out/_next/static/.htaccess The immutable cache for hashed build assets.
//   out/_headers               Netlify and Cloudflare Pages.
//
// Every .htaccess directive that needs a module sits inside <IfModule>, so a
// host without the module skips it instead of answering 500. There are no
// <If> blocks, because LiteSpeed supports them only partly.
//
// Netlify and Cloudflare Pages both join the values of a header that two
// matching _headers rules set. So only `/*` sets the security headers, and the
// Cache-Control rules are generated from the files in out/ so that exactly one
// rule matches any path: `/_next/static/*`, a `/dir/*` rule for a directory
// whose files share one cache rule and hold no index.html, and an exact rule
// for every other file and every directory URL. Cloudflare Pages reads at most
// MAX_HEADER_RULES rules, so exceeding it fails the build.
//
// Usage:  node scripts/static-hosting/write-host-files.mjs [--out <dir>]
//   <dir> defaults to `out`, relative to the working directory. Exits 1 if it
//   does not exist, otherwise writes the three files, prints one line, and
//   exits 0.

import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  CACHE_DEFAULT,
  CACHE_IMMUTABLE,
  CACHE_REVALIDATE,
  COMPRESSIBLE_TYPES,
  CONTENT_TYPES,
  cacheControlFor,
  IMMUTABLE_PREFIX,
  mediaType,
  REVALIDATE_EXTENSIONS,
  SECURITY_HEADERS,
} from "./policy.mjs";

export const NOTICE = "Generated by scripts/static-hosting/write-host-files.mjs from policy.mjs. Do not edit.";
export const HOST_FILES = [".htaccess", "_next/static/.htaccess", "_headers"];
export const MAX_HEADER_RULES = 100;

// A _headers path cannot hold whitespace or "*", and a segment starting with
// ":" is a placeholder, so a file named that way cannot be matched exactly.
const UNSAFE_SEGMENT = /[\s*]|^:/;

function quoted(name, value) {
  if (/["\\\r\n]/.test(value)) throw new Error(`policy value for ${name} cannot be quoted in .htaccess: ${value}`);
  return `"${value}"`;
}

const filesMatch = (extensions) => `\\.(${extensions.map((extension) => extension.slice(1)).join("|")})$`;

export function renderHtaccess() {
  const byType = new Map();
  for (const [extension, type] of Object.entries(CONTENT_TYPES)) {
    byType.set(mediaType(type), [...(byType.get(mediaType(type)) ?? []), extension]);
  }
  const utf8 = Object.keys(CONTENT_TYPES).filter((extension) => /charset=utf-8/i.test(CONTENT_TYPES[extension]));
  const security = Object.entries(SECURITY_HEADERS).map(
    ([name, value]) => `  Header always set ${name} ${quoted(name, value)}`,
  );
  return [
    `# ${NOTICE}`,
    "",
    "Options -Indexes",
    "DirectoryIndex index.html",
    "ErrorDocument 404 /404.html",
    "AddDefaultCharset UTF-8",
    "",
    "<IfModule mod_mime.c>",
    ...[...byType].map(([type, extensions]) => `  AddType ${type} ${extensions.join(" ")}`),
    `  AddCharset UTF-8 ${utf8.join(" ")}`,
    "</IfModule>",
    "",
    "<IfModule mod_headers.c>",
    ...security,
    `  Header set Cache-Control ${quoted("Cache-Control", CACHE_DEFAULT)}`,
    `  <FilesMatch "${filesMatch(REVALIDATE_EXTENSIONS)}">`,
    `    Header set Cache-Control ${quoted("Cache-Control", CACHE_REVALIDATE)}`,
    "  </FilesMatch>",
    "</IfModule>",
    "",
    "<IfModule mod_deflate.c>",
    "  <IfModule mod_filter.c>",
    `    AddOutputFilterByType DEFLATE ${COMPRESSIBLE_TYPES.join(" ")}`,
    "  </IfModule>",
    "</IfModule>",
    "",
  ].join("\n");
}

// The <FilesMatch> repeats the rule so that it also wins over the root file's
// document rule for any document that lands under _next/static.
export function renderStaticHtaccess() {
  const value = quoted("Cache-Control", CACHE_IMMUTABLE);
  return [
    `# ${NOTICE}`,
    "# Hashed build assets: a new build gives changed content a new file name.",
    "",
    "<IfModule mod_headers.c>",
    `  Header set Cache-Control ${value}`,
    `  <FilesMatch "${filesMatch(REVALIDATE_EXTENSIONS)}">`,
    `    Header set Cache-Control ${value}`,
    "  </FilesMatch>",
    "</IfModule>",
    "",
  ].join("\n");
}

// The entries a host serves: hidden files and the generated _headers are left
// out, so rerunning the writer gives the same result.
function servedEntries(directory, urlPrefix) {
  return readdirSync(directory)
    .filter((name) => !name.startsWith(".") && !(urlPrefix === "/" && name === "_headers"))
    .sort()
    .map((name) => {
      if (UNSAFE_SEGMENT.test(name)) throw new Error(`${urlPrefix}${name} cannot be written as a _headers path`);
      const stats = statSync(path.join(directory, name));
      return { name, file: stats.isFile(), directory: stats.isDirectory() };
    });
}

// The cache values of every file under a directory URL, and whether any
// directory in it serves an index.html.
function survey(directory, urlPrefix) {
  const values = new Set();
  let hasIndex = false;
  for (const entry of servedEntries(directory, urlPrefix)) {
    const url = `${urlPrefix}${entry.name}`;
    if (entry.file) {
      values.add(cacheControlFor(url));
      hasIndex ||= entry.name === "index.html";
    } else if (entry.directory) {
      const inner = survey(path.join(directory, entry.name), `${url}/`);
      for (const value of inner.values) values.add(value);
      hasIndex ||= inner.hasIndex;
    }
  }
  return { values, hasIndex };
}

function collectRules(directory, urlPrefix, rules) {
  const entries = servedEntries(directory, urlPrefix);
  if (entries.some((entry) => entry.file && entry.name === "index.html")) {
    rules.push({ pattern: urlPrefix, cacheControl: cacheControlFor(urlPrefix) });
  }
  for (const entry of entries) {
    const url = `${urlPrefix}${entry.name}`;
    if (entry.file) {
      rules.push({ pattern: url, cacheControl: cacheControlFor(url) });
      continue;
    }
    const child = path.join(directory, entry.name);
    const childUrl = `${url}/`;
    if (!entry.directory || childUrl === IMMUTABLE_PREFIX) continue;
    // An ancestor of _next/static is never rolled up, or its rule would
    // overlap `/_next/static/*`.
    if (IMMUTABLE_PREFIX.startsWith(childUrl)) {
      collectRules(child, childUrl, rules);
      continue;
    }
    const { values, hasIndex } = survey(child, childUrl);
    if (values.size === 1 && !hasIndex) rules.push({ pattern: `${childUrl}*`, cacheControl: [...values][0] });
    else if (values.size > 1 || hasIndex) collectRules(child, childUrl, rules);
  }
}

// The Cache-Control rules for a built site, in the order they are written.
export function cacheRules(outDir) {
  const rules = [{ pattern: `${IMMUTABLE_PREFIX}*`, cacheControl: CACHE_IMMUTABLE }];
  collectRules(path.resolve(outDir), "/", rules);
  if (rules.length + 1 > MAX_HEADER_RULES) {
    throw new Error(
      `_headers needs ${rules.length + 1} rules; Cloudflare Pages reads at most ${MAX_HEADER_RULES}. ` +
        "Group assets into directories so one /dir/* rule covers each.",
    );
  }
  return rules;
}

export function renderHeaders(rules) {
  const blocks = [
    [`# ${NOTICE}`],
    ["/*", ...Object.entries(SECURITY_HEADERS).map(([name, value]) => `  ${name}: ${value}`)],
    ...rules.map(({ pattern, cacheControl }) => [pattern, `  Cache-Control: ${cacheControl}`]),
  ];
  return `${blocks.map((lines) => lines.join("\n")).join("\n\n")}\n`;
}

// Writes the three host files into outDir and returns the number of _headers
// rules. Throws if outDir is not a directory.
export function writeHostFiles(outDir) {
  const root = path.resolve(outDir);
  let stats;
  try {
    stats = statSync(root);
  } catch {
    stats = null;
  }
  if (!stats?.isDirectory()) throw new Error(`${root} does not exist; run next build first`);
  const rules = cacheRules(root);
  mkdirSync(path.join(root, "_next", "static"), { recursive: true });
  writeFileSync(path.join(root, ".htaccess"), renderHtaccess());
  writeFileSync(path.join(root, "_next", "static", ".htaccess"), renderStaticHtaccess());
  writeFileSync(path.join(root, "_headers"), renderHeaders(rules));
  return rules.length + 1;
}

function main(argv) {
  const outFlag = argv.indexOf("--out");
  const outDir = path.resolve(outFlag >= 0 && argv[outFlag + 1] ? argv[outFlag + 1] : "out");
  try {
    const ruleCount = writeHostFiles(outDir);
    console.log(`host-files: wrote ${HOST_FILES.join(", ")} in ${outDir} (${ruleCount} _headers rules)`);
    return 0;
  } catch (error) {
    console.error(`host-files: ${error.message}`);
    return 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
